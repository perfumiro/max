import { readFileSync, mkdirSync, copyFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const app = fileURLToPath(new URL('../', import.meta.url));
const catalog = JSON.parse(readFileSync(path.join(app, 'website-ipordise/catalog.json'), 'utf8'));
const images = [...new Set(catalog.products.flatMap(p => [p.image, ...(p.gallery || [])]).filter(url => typeof url === 'string' && /\.(png|jpe?g|jfif|webp)$/i.test(url)))].sort();
const entries = images.map((url, index) => {
  if (!url.startsWith('/assets/') || !/\.(png|jpe?g|jfif|webp)$/i.test(url)) throw Error('Unsupported bundled image: ' + url);
  const filename = String(index).padStart(3, '0') + path.extname(url).toLowerCase().replace('.jfif', '.jpg');
  const destination = path.join(app, 'assets/catalog', filename);
  mkdirSync(path.dirname(destination), {recursive:true});
  copyFileSync(path.join(app, '..', url.slice(1)), destination);
  return '  ' + JSON.stringify(url) + ': require(' + JSON.stringify('../../assets/catalog/' + filename) + '),';
});
writeFileSync(path.join(app, 'src/generated/productImages.ts'), '// Generated by scripts/generate-product-images.mjs. Static requires include photos in native releases.\nexport const bundledProductImages: Record<string, number> = {\n' + entries.join('\n') + '\n};\n');
console.log('Bundled ' + images.length + ' product photos');
