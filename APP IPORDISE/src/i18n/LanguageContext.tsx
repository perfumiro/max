type NavLabels = {
  home: string;
  offers: string;
  shop: string;
  help: string;
  account: string;
};
type LanguageValue = {
  language: AppLanguage;
  rtl: boolean;
  setLanguage: (language: AppLanguage) => Promise<void>;
  nav: NavLabels;
  t: (key: string) => string;
};
const LanguageContext = createContext<LanguageValue | null>(null);

async function readLanguage(): Promise<AppLanguage> {
  try {
    if (Platform.OS === "web" && typeof location !== "undefined") {
      const requested = new URLSearchParams(location.search).get("lang");
      if (requested === "en" || requested === "fr") return requested;
    }
    const value =
      Platform.OS === "web"
        ? localStorage.getItem(STORAGE_KEY)
        : await SecureStore.getItemAsync(STORAGE_KEY);
    return value === "en" || value === "fr" ? value : "fr";
  } catch {
    return "fr";
  }
}

export function LanguageProvider({ children }: PropsWithChildren) {
  const [language, setCurrent] = useState<AppLanguage>("fr");
  useEffect(() => {
    void readLanguage().then(setCurrent);
  }, []);
  useEffect(() => {
    if (language === "ar") setCurrent("fr");
  }, [language]);
  useEffect(() => {
    if (Platform.OS === "web" && typeof document !== "undefined") {
      document.documentElement.lang = language;
      document.documentElement.dir = language === "ar" ? "rtl" : "ltr";
    }
  }, [language]);
  const value = useMemo<LanguageValue>(
    () => ({
      language,
      rtl: language === "ar",
      nav: labels[language],
      t: (key) =>
        brandMessages[language][key] || accountMessages[language][key] || brandMessages.en[key] || accountMessages.en[key] || key,
      setLanguage: async (next) => {
        if (next === "ar") next = "fr";
        setCurrent(next);
        try {
          if (Platform.OS === "web") localStorage.setItem(STORAGE_KEY, next);
          else await SecureStore.setItemAsync(STORAGE_KEY, next);
        } catch {
          /* preference remains active for this session */
        }
      },
    }),
    [language],
  );
  return (
    <LanguageContext.Provider value={value}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  const value = useContext(LanguageContext);
  if (!value)
    throw new Error("useLanguage must be used inside LanguageProvider");
  return value;
}
