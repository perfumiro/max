        assert.equal(await page.locator('#productPrice').isVisible(), false);
        await page.locator('#sizeSelector [data-size-key="50ml"]').click();
        assert.match(await page.locator('#sizeSelector [data-size-key="50ml"] .spill-price').innerText(), /Price soon/i);
