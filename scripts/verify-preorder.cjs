        assert.equal(await page.locator('#addToCartBtn').isVisible(), false);
        assert.match(await page.locator('#arrivalPanel button').innerText(), /Ask about/i);
        assert.doesNotMatch(await page.locator('#arrivalPanel').innerText(), /ordering catalogue|not been published/);
